/**
 * LinkItem의 iconType에 따라 적절한 아이콘 컴포넌트를 렌더링하는 헬퍼
 */
export function renderLinkIcon(iconType: IconType, className = "w-5 h-5") {
  switch (iconType) {
    case "globe":
      return <IconGlobe className={className} />;
    case "github":
      return <IconGitHub className={className} />;
    case "blog":
      return <IconSparkles className={className} />;
    case "mail":
      return <IconMail className={className} />;
    case "coffee":
      return <IconCoffee className={className} />;
    case "file-text":
      return <IconFileText className={className} />;
    case "instagram":
      return <IconInstagram className={className} />;
    case "youtube":
      return <IconYouTube className={className} />;
    case "twitter":
      return <IconTwitter className={className} />;
    case "linkedin":
      return <IconLinkedIn className={className} />;
    case "discord":
      return <IconDiscord className={className} />;
    case "store":
      return <IconStore className={className} />;
    case "code":
      return <IconCode className={className} />;
    case "briefcase":
      return <IconBriefcase className={className} />;
    case "sparkles":
      return <IconSparkles className={className} />;
    case "link":
    default:
      return <IconLink className={className} />;
  }
}
